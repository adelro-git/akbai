/**
 * Chat API Validation Schemas
 * Feature: KA Chat (Build 1+)
 * Role: Request/response validation and type generation
 *
 * Responsibility: Define Zod schemas for POST /api/ka/chat requests and responses.
 * Schemas are the single source of truth — TypeScript types are derived from them.
 * Ensures type safety from request validation through response serialization.
 *
 * Dependencies: Zod library
 * Tested by: QA — invalid request rejection, response type safety
 */

import { z } from 'zod';

/**
 * Request body for POST /api/ka/chat
 *
 * - message: User's chat message (required, non-empty string, max 2000 chars)
 * - scope: Optional domain scope hint (financial, birkto, communication, etc.)
 *   Used for multi-domain routing in Phase 2+
 */
export const ChatRequestSchema = z.object({
  message: z
    .string()
    .min(1, 'Message cannot be empty')
    .max(2000, 'Message too long (max 2000 characters)'),
  scope: z
    .enum(['financial', 'birkto', 'communication', 'general'])
    .optional()
    .default('general'),
});

export type ChatRequest = z.infer<typeof ChatRequestSchema>;

/**
 * KA's chat response structure.
 *
 * - content: KA's message text (Taglish, warm, grounded in data)
 * - inputTokens: Tokens consumed from Claude API (for cost tracking)
 * - outputTokens: Tokens generated by Claude (for cost tracking)
 * - model: Model used (haiku or sonnet, for audit trail)
 * - costCentavos: Cost of this interaction in Philippine centavos
 */
export const ChatResponseSchema = z.object({
  content: z.string().min(1, 'Response cannot be empty'),
  inputTokens: z.number().int().nonnegative(),
  outputTokens: z.number().int().nonnegative(),
  model: z.string(),
  costCentavos: z.number().int().nonnegative(),
});

export type ChatResponse = z.infer<typeof ChatResponseSchema>;

/**
 * Standard API response envelope for success.
 *
 * Pattern: { success: true, data: T }
 * Used by all AKBai API routes for consistent client parsing.
 */
export const ApiSuccessEnvelopeSchema = <T extends z.ZodType>(schema: T) =>
  z.object({
    success: z.literal(true),
    data: schema,
  });

/**
 * Standard API response envelope for error.
 *
 * Pattern: { success: false, error: { code, message, message_tl?, details? } }
 * - code: Machine-readable error code (VALIDATION_ERROR, AUTH_REQUIRED, AI_CIRCUIT_OPEN, etc.)
 * - message: English error message (for logs and QA)
 * - message_tl: Taglish user-facing message (warm, actionable)
 * - details: Optional structured error details (e.g., Zod validation issues)
 */
export const ApiErrorEnvelopeSchema = z.object({
  success: z.literal(false),
  error: z.object({
    code: z.string(),
    message: z.string(),
    message_tl: z.string().optional(),
    details: z.record(z.any()).optional(),
  }),
});

/**
 * Conversation entry stored in ka_conversations table.
 *
 * - id: UUID primary key
 * - user_id: User who sent the message
 * - role: 'user' (user message) or 'assistant' (KA response)
 * - content: The message text
 * - scope: Domain/context (financial, birkto, communication, general)
 * - input_tokens: Tokens from Claude (for KA responses only)
 * - output_tokens: Tokens generated by Claude (for KA responses only)
 * - model: Claude model used (haiku or sonnet)
 * - cost_centavos: Cost of the interaction in Philippine centavos
 * - created_at: Timestamp (auto-set by Supabase)
 * - updated_at: Timestamp (auto-updated by trigger)
 * - deleted_at: Soft delete timestamp (null while active)
 */
export const ConversationMessageSchema = z.object({
  id: z.string().uuid(),
  user_id: z.string().uuid(),
  role: z.enum(['user', 'assistant']),
  content: z.string().min(1),
  scope: z.enum(['financial', 'birkto', 'communication', 'general']).default('general'),
  input_tokens: z.number().int().nonnegative().nullable(),
  output_tokens: z.number().int().nonnegative().nullable(),
  model: z.string().nullable(),
  cost_centavos: z.number().int().nonnegative().nullable(),
  created_at: z.string().datetime(),
  updated_at: z.string().datetime().nullable(),
  deleted_at: z.string().datetime().nullable(),
});

export type ConversationMessage = z.infer<typeof ConversationMessageSchema>;

/**
 * User profile data needed to build KA persona prompt.
 * Fetched from users table and businesses table.
 */
export const UserProfileSchema = z.object({
  id: z.string().uuid(),
  email: z.string().email(),
  first_name: z.string().min(1),
  subscription_tier: z.enum(['free', 'pro', 'business']),
  business_id: z.string().uuid().nullable(),
  created_at: z.string().datetime(),
});

export type UserProfile = z.infer<typeof UserProfileSchema>;

export const BusinessProfileSchema = z.object({
  id: z.string().uuid(),
  name: z.string().min(1),
  type: z.string().min(1), // e.g., "home bakery", "sari-sari store"
  created_at: z.string().datetime(),
});

export type BusinessProfile = z.infer<typeof BusinessProfileSchema>;
